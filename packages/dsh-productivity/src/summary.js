export function summary_prompt(cwd) {
    const destination = cwd
        ? `请实际把总结保存为 UTF-8 Markdown 文件，放在本会话工作区 ${JSON.stringify(cwd)} 内。文件名使用“会话总结-YYYYMMDD-HHmmss.md”，已有同名文件则追加序号，禁止覆盖原有文件。完成后在回复中给出文件绝对路径和可点击的 Markdown 链接。若工作区无法写入，说明原因并在回复中提供完整 Markdown 内容，不要改写到其他目录。`
        : "此会话没有绑定本地工作区，请直接在回复中提供完整 Markdown 内容（使用 markdown 代码块），不要写入其他目录。";
    return `请根据当前会话生成一份可用于归档和后续继续工作的中文 Markdown 总结。

仅依据本会话已经出现的信息，按实际内容组织：用户目标与约束、已完成的工作、关键决策和理由、涉及的文件与重要变更、已执行的验证及结果、仍存在的问题、待办事项与下一步。区分已完成与计划、已验证与尚未验证；不要杜撰结果。保留继续工作所需的准确路径和必要命令，但不要复制 API Key、令牌、密码或其他凭据，涉及凭据的位置替换为 <REDACTED>。

${destination}

本次只生成总结，不清理文件、不修改业务代码、不停止当前任务。`;
}
